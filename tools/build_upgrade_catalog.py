"""Regenerate the Godot catalog from design/weapon_upgrades_v2.json."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'design/weapon_upgrades_v2.json').read_text())
entries = data['shared'] | data['ranged'] | data['melee']
owners = {}
for weapon, cards in data['weapons'].items():
    entries.update(cards)
    owners.update({key: weapon for key in cards})
entries['piercing'] = ['Meteor Size', '+20% base meteor radius', 5]
q = lambda value: json.dumps(value, ensure_ascii=False)
constants = {
    'RANGED': ['bow', 'crossbow', 'wand', 'spear', 'chakram'],
    'MELEE': ['sword', 'dual_axe', 'club', 'hammer'],
    'SHARED': list(data['shared']), 'RANGED_ONLY': list(data['ranged']),
    'MELEE_ONLY': list(data['melee']),
    'UPGRADES': {key: value[:2] for key, value in entries.items()},
    'CAPS': {key: value[2] for key, value in entries.items() if value[2]},
    'OWNERS': owners, 'PAIRS': data['mutually_exclusive'], 'ACTIVE': list(entries),
}
text = 'extends RefCounted\n## Generated by tools/build_upgrade_catalog.py; edit design/weapon_upgrades_v2.json.\n'
text += ''.join(f'const {name} := {q(value)}\n' for name, value in constants.items())
text += '''static func opposite(id: String) -> String:
	for pair in PAIRS:
		if pair.has(id): return pair[1] if pair[0]==id else pair[0]
	return ""
static func signature(id: String) -> bool: return not opposite(id).is_empty()
'''
(ROOT / 'scripts/upgrade_catalog.gd').write_text(text)

# Keep the user's editable plain-text list in sync; rarity design remains open.
lines = ['CURRENT RUN UPGRADES — V2', '',
         '65 catalog entries, including the meteor-only size card.',
         'Previous list: design/archive/upgrades_v1/UPGRADES_TO_EDIT.txt.txt',
         'Edit design/weapon_upgrades_v2.json to change the generated game catalog.',
         'Rarity fields are reserved for the future rarity rework.', '']
groups = [('ALL WEAPONS', data['shared']), ('RANGED ONLY', data['ranged']),
          ('MELEE ONLY', data['melee'])]
groups += [(weapon.upper().replace('_', ' '), cards) for weapon, cards in data['weapons'].items()]
groups += [('METEOR ONLY', {'piercing': entries['piercing']})]
number = 0
for heading, cards in groups:
    lines += [heading, '']
    for key, (name, description, cap) in cards.items():
        number += 1
        lines += [f'{number}. {name}', f'   ID: {key}', f'   Effect: {description}',
                  f'   Cap: {cap or "Repeatable while injured"}',
                  '   Rarity: ' + ('Rare' if key == 'second_chance' else ''), '']
(ROOT / 'UPGRADES_TO_EDIT.txt').write_text('\n'.join(line.rstrip() for line in lines))
